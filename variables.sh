#! /usr/bin/bash

# ************* System Variables *************

# These variables are mainly defined in CAPITAL letters. 
# These variables are by default defined by the system & also maintained by the System.

# We can access these variables by using the $ sign before the variable name.

echo "Home directory is: $HOME"
echo "Name of the Bash: $BASH"
echo "BASH Version is: $BASH_VERSION"
echo "Current Working Directory is: $PWD"

# ************* User Defined Variables *************

# These Type of variables are defined by the user.

# Syntax: variable_name=value


name=Mark

echo "Name is: $name"
